# Crear un arreglo
frutas = ["Mango", "Naranja", "Plátano", "Fresa", "Guayaba", "Piña"]

# Mostrar todo el arreglo
print(frutas)

# Mostrar un elemento
print(frutas[0])

# Agregar un elemento
frutas.append("Melón")

# Eliminar un elemento
frutas.remove("Naranja")

# Mostrar el arreglo actualizado
print(frutas)